def safe_code(raw):
    code = (raw or "").strip()
    if not (4 <= len(code) <= 24) or not all(c.isascii() and (c.isalnum() or c in '-_') for c in code):
        raise ValueError("참가자 코드는 영문/숫자/-/_ 4~24자로 입력해 주세요. 이름·연락처는 사용하지 마세요.")
    return code


def identifier(code, salt):
    return hashlib.sha256((salt + ':' + safe_code(code).lower()).encode()).hexdigest()


def study_level(previous_completed):
    return min(previous_completed + 1, max(LEVELS))


def select_cases(participant_hash, run_number):
    level = study_level(run_number - 1)
    size = LEVELS[level][1]
    pool = [x for x in CASES if x['level'] == level]
    rnd = random.Random(f"{participant_hash}:{run_number}:emotiongap-v2")
    return rnd.sample(pool, size)


def summarize(records):
    if not records:
        return {"count": 0, "agreement_before": None, "agreement_after": None, "ai_reference_before": None, "ai_reference_after": None, "ai_changes": None, "human_changes": None}
    n = len(records)
    def ratio(predicate):
        return sum(1 for r in records if predicate(r)) / n
    return {
        "count": n,
        "agreement_before": ratio(lambda r:r['human_before']==r['ai_before']),
        "agreement_after": ratio(lambda r:r['human_after']==r['ai_after']),
        "ai_reference_before": ratio(lambda r:r['ai_before']==r['reference']),
        "ai_reference_after": ratio(lambda r:r['ai_after']==r['reference']),
        "ai_changes": ratio(lambda r:r['ai_before']!=r['ai_after']),
        "human_changes": ratio(lambda r:r['human_before']!=r['human_after']),
    }


def parse_ai(raw):
    text = raw.strip()
    if text.startswith('```'):
        text = text.split('\n', 1)[-1].rsplit('```', 1)[0].strip()
    obj = json.loads(text)
    if not isinstance(obj, dict) or obj.get('emotion') not in EMOTIONS or not isinstance(obj.get('reason'), str):
        raise ValueError("AI가 올바른 감정 레이블 또는 설명을 반환하지 않았습니다.")
    return {'emotion':obj['emotion'], 'reason':obj['reason'][:180]}
